# E:\BPCL office\Project2\sync_photos.ps1
# Script to synchronize site folders from Google Drive and copy photos locally for GitHub Pages

$indexHtmlPath = "E:\BPCL office\Project2\index.html"
$sitesDetailsPath = "G:\My Drive\TL-PATIL- 2026\IFMS\Sites Details"
$localPhotosPath = "E:\BPCL office\Project2\Photos"
$outputJsPath = "E:\BPCL office\Project2\photos_data.js"

# Create destination base path if it doesn't exist
if (!(Test-Path -Path $localPhotosPath)) {
    Write-Host "Creating local Photos folder: $localPhotosPath" -ForegroundColor Yellow
    New-Item -Path $localPhotosPath -ItemType Directory -Force | Out-Null
}

Write-Host "Reading index.html to fetch dealer list..." -ForegroundColor Cyan
if (!(Test-Path -Path $indexHtmlPath)) {
    Write-Error "index.html not found at $indexHtmlPath!"
    exit
}

$content = Get-Content -Path $indexHtmlPath -Raw

# Extract dealersData block
$startIndex = $content.IndexOf("const dealersData = [")
if ($startIndex -eq -1) {
    Write-Error "Could not find dealersData block in index.html!"
    exit
}

$endIndex = $content.IndexOf("];", $startIndex)
$dealersBlock = $content.Substring($startIndex, $endIndex - $startIndex)

# Match each dealer object
$dealerPattern = "(?s)\{[^{}]+\}"
$dealerMatches = [regex]::Matches($dealersBlock, $dealerPattern)

Write-Host "Found $($dealerMatches.Count) dealers. Syncing directories..." -ForegroundColor Cyan

$photosMap = @{}
$newFoldersCount = 0
$copiedFilesCount = 0

foreach ($match in $dealerMatches) {
    $dealerText = $match.Value
    
    # Extract CC Number
    $ccMatch = [regex]::Match($dealerText, "ccNumber:\s*'([^']+)'")
    if (!$ccMatch.Success) { continue }
    $ccNumber = $ccMatch.Groups[1].Value
    
    # Extract Outlet Name
    $nameMatch = [regex]::Match($dealerText, "outletName:\s*'([^']+)'")
    if (!$nameMatch.Success) { continue }
    $outletName = $nameMatch.Groups[1].Value
    
    # Check if folder exists starting with CC Number on Google Drive
    $folder = Get-ChildItem -Path $sitesDetailsPath -Directory -Filter "$ccNumber*" | Select-Object -First 1
    
    $folderName = ""
    if ($folder) {
        $folderName = $folder.Name
    } else {
        # Create missing folder name
        $sanitizedName = $outletName -replace '[^A-Za-z0-9 ]', ''
        $sanitizedName = $sanitizedName.Trim() -replace '\s+', '_'
        $sanitizedName = $sanitizedName.ToUpper()
        $folderName = "${ccNumber}_${sanitizedName}"
        
        # Create on Google Drive
        $newFolderPath = Join-Path -Path $sitesDetailsPath -ChildPath $folderName
        Write-Host "Creating missing folder on Google Drive: $folderName" -ForegroundColor Green
        New-Item -Path $newFolderPath -ItemType Directory -Force | Out-Null
        $newFoldersCount++
    }
    
    # Ensure matching local workspace folder exists
    $localFolderPath = Join-Path -Path $localPhotosPath -ChildPath $folderName
    if (!(Test-Path -Path $localFolderPath)) {
        New-Item -Path $localFolderPath -ItemType Directory -Force | Out-Null
    }
    
    # Scan for photos in Google Drive folder
    $fullFolderPath = Join-Path -Path $sitesDetailsPath -ChildPath $folderName
    $photoFiles = Get-ChildItem -Path $fullFolderPath -File | Where-Object { $_.Extension -match '^\.(jpg|jpeg|png|webp|gif)$' }
    
    $photosList = @()
    foreach ($file in $photoFiles) {
        # Copy photo from Google Drive to local project Photos directory
        $destFilePath = Join-Path -Path $localFolderPath -ChildPath $file.Name
        if (!(Test-Path -Path $destFilePath) -or (Get-Item -Path $file.FullName).LastWriteTime -gt (Get-Item -Path $destFilePath).LastWriteTime) {
            Write-Host "Copying: $($file.Name) to local project workspace..." -ForegroundColor Green
            Copy-Item -Path $file.FullName -Destination $destFilePath -Force
            $copiedFilesCount++
        }
        $photosList += $file.Name
    }
    
    $photosMap[$ccNumber] = @{
        folderName = $folderName
        folderPath = "./Photos/$folderName" # Relative web path
        photos = $photosList
    }
}

# Convert map to JSON
$json = $photosMap | ConvertTo-Json -Depth 5

# Format as JavaScript file content
$jsContent = @"
// Automatically generated by sync_photos.ps1
// Contains the photo metadata for each retail outlet matching folders relatively inside ./Photos/

const photosData = $json;
"@

# Write to file
Set-Content -Path $outputJsPath -Value $jsContent -Encoding utf8
Write-Host "Sync complete! Saved relative paths to $outputJsPath" -ForegroundColor Cyan
Write-Host "Created $newFoldersCount folders. Copied $copiedFilesCount files." -ForegroundColor Cyan
